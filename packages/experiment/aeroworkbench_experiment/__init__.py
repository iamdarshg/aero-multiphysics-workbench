"""Generic experiment, DAQ, system-identification, and HIL evidence layer.

This package closes the simulation-to-reality loop for any bench, wind-tunnel,
thrust-stand, structural, thermal, or flight/vehicle test. It ingests rig and
test measurements as first-class provenance-backed evidence, records sensor and
calibration provenance, performs reproducible synchronization and derived-signal
processing, compares measurements to simulation result envelopes by design and
operating condition, identifies bounded model parameters with a distinct
calibration/validation split, and drives controllers against recorded or live
hardware streams. It is application-agnostic and encodes no product-specific
assumptions.

Public API (other workstreams import these exact paths):

    from aeroworkbench_experiment import (
        ExperimentPlan, TestArticle, OperatingCondition, EnvironmentalState,
        SensorSpec, ChannelSpec, CalibrationRevision, SamplingSpec,
        condition_key, ingest_tabular, MeasurementDataset, MeasurementChannel,
        TabularAdapter, IngestionAdapter, RawArtifact,
        channel_provenance, dataset_sensor_provenance, ChannelProvenance,
        resample, align_to_trigger, apply_filter, spectrum, order_spectrum,
        segment_cycles, segment_events, FilterSpec, Spectrum, OrderSpectrum,
        SimulationResultEnvelope, SimulationChannel, compare_dataset,
        match_dataset, require_match, scalar_residual, compare_spectra,
        ParameterBound, Observation, split_calibration_validation,
        estimate_parameters, identify, IdentificationReport,
        Frame, ReplayStream, replay, run_hardware, require_hil_hardware,
        EvidenceRecord, measurement_evidence, simulation_evidence,
        corroborate, promote_to_native,
        EvidenceKind, EvidenceFidelity, Validity, SoftwareIdentity,
        CapabilityUnavailable, ExperimentError,
    )

Every result carries source/fidelity/units/validity/input-hash/software-identity/
provenance. Measurement and simulation evidence are never conflated, and no
native solver or DAQ hardware path exists without a real backend: those requests
fail closed. Nothing is fabricated.
"""

